import MarkdownIt from "markdown-it";
import type Token from "markdown-it/lib/token.mjs";
import { type MemosImage, type MemosMoment, safeMemosURL } from "./memos-utils";

function hideStandaloneTagLines(tokens: Token[], tags: Set<string>): Token[] {
	const lines: { tokens: Token[]; separator?: Token; linked: boolean }[] = [
		{ tokens: [], linked: false },
	];
	let linkDepth = 0;
	for (const token of tokens) {
		const line = lines[lines.length - 1];
		if (token.type === "softbreak" || token.type === "hardbreak") {
			line.separator = token;
			lines.push({ tokens: [], linked: linkDepth > 0 });
			continue;
		}
		if (token.type === "link_open") linkDepth++;
		if (linkDepth > 0) line.linked = true;
		line.tokens.push(token);
		if (token.type === "link_close") linkDepth--;
	}
	const visible = lines.filter((line) => {
		if (line.linked || line.tokens.some((token) => token.type !== "text"))
			return true;
		const words = line.tokens
			.map((token) => token.content)
			.join("")
			.trim()
			.split(/\s+/);
		return !words.every((word) => tags.has(word));
	});
	return visible.flatMap((line, index) => [
		...line.tokens,
		...(index < visible.length - 1 && line.separator ? [line.separator] : []),
	]);
}

// Only HTML generated by markdown-it is inserted into the page. Raw HTML is disabled.
export function renderMemosContent(moment: MemosMoment, serverURL: string) {
	const parser = new MarkdownIt({ html: false, linkify: true, breaks: true });
	const tags = new Set(moment.tags.map((tag) => `#${tag}`));
	// Preserve escaped text before markdown-it merges it into ordinary text.
	parser.core.ruler.before("text_join", "hide_standalone_tags", (state) => {
		for (let index = 0; index < state.tokens.length; index++) {
			const token = state.tokens[index];
			if (
				token.type !== "inline" ||
				token.level !== 1 ||
				!token.children ||
				state.tokens[index - 1]?.type !== "paragraph_open"
			)
				continue;
			token.children = hideStandaloneTagLines(token.children, tags);
			if (
				token.children.length === 0 &&
				state.tokens[index + 1]?.type === "paragraph_close"
			) {
				state.tokens.splice(index - 1, 3);
				index -= 2;
			}
		}
	});
	const tokens = parser.parse(moment.content, {});
	const images: MemosImage[] = [];
	const seen = new Set<string>();
	const addImage = (image: MemosImage) => {
		if (seen.has(image.src)) return;
		seen.add(image.src);
		images.push(image);
	};
	const attachments = new Map(moment.images.map((image) => [image.src, image]));
	const heading = tokens.findIndex(
		(token) => token.type === "heading_open" && token.tag === "h1",
	);
	const headingTitle = tokens[heading + 1]?.children
		?.filter((token) => token.type === "text" || token.type === "code_inline")
		.map((token) => token.content)
		.join("")
		.trim();
	if (
		moment.title &&
		heading >= 0 &&
		headingTitle === moment.title &&
		!tokens[heading + 1]?.children?.some((token) => token.type === "image")
	)
		tokens.splice(heading, 3);
	for (const token of tokens) {
		if (!token.children) continue;
		let linkDepth = 0;
		token.children = token.children.filter((child) => {
			if (child.type === "link_open") linkDepth++;
			if (child.type === "link_close") linkDepth--;
			if (child.type !== "image") return true;
			const src = safeMemosURL(child.attrGet("src") || "", serverURL);
			if (src && linkDepth > 0) {
				// Linked images keep their destination and stay in the article.
				child.attrSet("src", src);
				child.attrSet("loading", "lazy");
				child.attrSet("decoding", "async");
				seen.add(src);
				return true;
			}
			if (src) {
				const attached = attachments.get(src);
				addImage(
					attached
						? { ...attached, alt: child.content || attached.alt }
						: { src, thumbnail: src, alt: child.content },
				);
			}
			return false;
		});
	}
	for (const image of moment.images) addImage(image);
	parser.renderer.rules.link_open = (links, index, options, _env, self) => {
		const token = links[index];
		const href = token.attrGet("href") || "";
		const safe = safeMemosURL(href, serverURL, true);
		if (safe) token.attrSet("href", href.startsWith("#") ? href : safe);
		else token.attrSet("href", "#");
		token.attrSet("rel", "noopener noreferrer nofollow");
		if (!href.startsWith("#")) token.attrSet("target", "_blank");
		return self.renderToken(links, index, options);
	};
	return {
		html: parser.renderer.render(tokens, parser.options, {}),
		images,
	};
}
